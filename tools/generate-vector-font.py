"""Compile pinned OFL outlines into ProjectZ Sans vector commands, not a font file.

Requires fonttools==4.67.0. Downloads build inputs into a supplied temporary folder.
Usage: python tools/generate-vector-font.py --cache /path/outside/source/tree
"""
import argparse
import base64
import gzip
import hashlib
import io
from pathlib import Path
import struct
import urllib.request
import zipfile
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen

URL = 'https://github.com/rsms/inter/releases/download/v4.1/Inter-4.1.zip'
SHA256 = '9883fdd4a49d4fb66bd8177ba6625ef9a64aa45899767dde3d36aa425756b11e'
ROOT = Path(__file__).resolve().parents[1]

class OutlinePen(BasePen):
    def __init__(self, glyphs):
        super().__init__(glyphs)
        self.commands = []
    def _moveTo(self, p): self.commands.append((0, p))
    def _lineTo(self, p): self.commands.append((1, p))
    def _curveToOne(self, a, b, c): self.commands.append((2, a + b + c))
    def _qCurveToOne(self, a, b): self.commands.append((3, a + b))
    def _closePath(self): self.commands.append((4, ()))
    def _endPath(self): self.commands.append((4, ()))

def compile_face(data):
    font = TTFont(io.BytesIO(data))
    names = font.getGlyphOrder()
    ids = {name: i for i, name in enumerate(names)}
    output = io.BytesIO()
    def write(fmt, *values): output.write(struct.pack('<' + fmt, *values))
    write('HhhhH', font['head'].unitsPerEm, font['hhea'].ascent,
          font['hhea'].descent, font['hhea'].lineGap, len(names))
    glyphs = font.getGlyphSet()
    for name in names:
        pen = OutlinePen(glyphs)
        glyphs[name].draw(pen)
        write('HH', font['hmtx'][name][0], len(pen.commands))
        for command, coords in pen.commands:
            write('B', command)
            if coords: write('f' * len(coords), *coords)
    cmap = font.getBestCmap()
    write('I', len(cmap))
    for codepoint, name in sorted(cmap.items()): write('IH', codepoint, ids[name])
    gpos = font['GPOS'].table
    indexes = sorted({i for feature in gpos.FeatureList.FeatureRecord if feature.FeatureTag == 'kern'
                      for i in feature.Feature.LookupListIndex})
    subtables = []
    for index in indexes:
        lookup = gpos.LookupList.Lookup[index]
        for sub in lookup.SubTable:
            kind = lookup.LookupType
            if kind == 9: kind, sub = sub.ExtensionLookupType, sub.ExtSubTable
            if kind == 2: subtables.append(sub)
    write('H', len(subtables))
    for sub in subtables:
        write('B', sub.Format)
        if sub.Format == 1:
            pairs = [(ids[first], ids[pair.SecondGlyph], getattr(pair.Value1, 'XAdvance', 0))
                     for first, pairset in zip(sub.Coverage.glyphs, sub.PairSet)
                     for pair in pairset.PairValueRecord]
            write('I', len(pairs))
            for a, b, advance in pairs: write('HHh', a, b, advance)
        else:
            write('H', len(sub.Coverage.glyphs))
            for name in sub.Coverage.glyphs: write('H', ids[name])
            for classes in (sub.ClassDef1.classDefs, sub.ClassDef2.classDefs):
                for name in names: write('H', classes.get(name, 0))
            write('HH', sub.Class1Count, sub.Class2Count)
            for row in sub.Class1Record:
                for pair in row.Class2Record: write('h', getattr(pair.Value1, 'XAdvance', 0))
    return output.getvalue()

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--cache', type=Path, required=True)
    args = parser.parse_args()
    args.cache.mkdir(parents=True, exist_ok=True)
    archive = args.cache / 'Inter-4.1.zip'
    if not archive.exists(): urllib.request.urlretrieve(URL, archive)
    if hashlib.sha256(archive.read_bytes()).hexdigest() != SHA256:
        raise ValueError('Pinned Inter archive hash does not match')
    with zipfile.ZipFile(archive) as source:
        faces = [compile_face(source.read('extras/otf/Inter-' + weight + '.otf'))
                 for weight in ('Regular', 'SemiBold', 'Bold')]
        license_dir = ROOT / 'ThirdParty' / 'ProjectZSans'
        license_dir.mkdir(parents=True, exist_ok=True)
        (license_dir / 'OFL.txt').write_bytes(source.read('LICENSE.txt'))
    data = b'PZV1' + b''.join(struct.pack('<I', len(face)) + face for face in faces)
    encoded = base64.b64encode(gzip.compress(data, mtime=0)).decode('ascii')
    chunks = [encoded[i:i+16000] for i in range(0, len(encoded), 16000)]
    result = '// Generated by tools/generate-vector-font.py. See ThirdParty/ProjectZSans.\n'
    result += 'namespace ProjectZ.VectorText;\ninternal static class OutlineData {\n'
    result += '    internal static readonly string[] Chunks = {\n'
    result += ''.join('        "' + part + '",\n' for part in chunks)
    result += '    };\n}\n'
    (ROOT / 'Project Z Vector Text' / 'OutlineData.g.cs').write_text(result, encoding='utf-8', newline='\n')
    print(f'Compiled three weights: {len(data):,} bytes of vector commands, {len(encoded):,} base64 characters')

if __name__ == '__main__': main()
