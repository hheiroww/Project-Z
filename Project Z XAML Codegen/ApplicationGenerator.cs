using System.Globalization;
using System.Text.Json;
using System.Text.RegularExpressions;
using System.Xml.Linq;

internal static class ApplicationGenerator
{
    internal static int Run(string directory)
    {
        try
        {
            var settings = File.ReadAllLines(Path.Combine(directory, "settings")).Where(line => line.Length > 0).Select(line => line.Split('=', 2)).ToDictionary(parts => parts[0], parts => parts.Length == 2 ? parts[1] : "", StringComparer.Ordinal);
            var vb = settings.GetValueOrDefault("Language") == "VB";
            var source = Generate(settings, vb);
            var path = Path.Combine(directory, vb ? "Application.vb" : "Application.cs");
            if (!File.Exists(path) || File.ReadAllText(path) != source) File.WriteAllText(path, source);
            return 0;
        }
        catch (Exception error) { Console.Error.WriteLine("Project-Z application settings: " + error.Message); return 1; }
    }
    static string TypeName(string name)
    {
        if (!Regex.IsMatch(name, @"^[_\p{L}][_\p{L}\p{N}]*(\.[_\p{L}][_\p{L}\p{N}]*)*$")) throw new ArgumentException("Select a fully qualified window/application type.");
        return name;
    }
    static string Generate(Dictionary<string, string> values, bool vb)
    {
        int Integer(string key, int fallback, int maximum = 16384) => values.TryGetValue(key, out var value) && int.TryParse(value, NumberStyles.Integer, CultureInfo.InvariantCulture, out var number) && number >= 1 && number <= maximum ? number : values.ContainsKey(key) ? throw new ArgumentException(key + " is out of range.") : fallback;
        bool Boolean(string key, bool fallback = false) => values.TryGetValue(key, out var value) ? bool.TryParse(value, out var flag) ? flag : throw new ArgumentException(key + " must be true or false.") : fallback;
        string Literal(string value) => vb ? "\"" + value.Replace("\"", "\"\"") + "\"" : JsonSerializer.Serialize(value);
        var mainWindow = values.GetValueOrDefault("MainWindow", "Default");
        var applicationType = values.GetValueOrDefault("ApplicationType", "");
        var shutdown = values.GetValueOrDefault("ShutdownMode", "Default");
        if (shutdown is not ("Default" or "OnLastWindowClose" or "OnMainWindowClose" or "OnExplicitShutdown")) throw new ArgumentException("Unknown shutdown mode.");
        var prefix = vb ? "Global." : "global::";
        var native = prefix + "ProjectZ.WpfCompatibility.";
        var application = applicationType.Length == 0 ? native + "Application" : prefix + TypeName(applicationType);
        string Bool(string key, bool fallback = false) => Boolean(key, fallback) ? vb ? "True" : "true" : vb ? "False" : "false";
        var color = values.GetValueOrDefault("BackgroundColor", "#000000").TrimStart('#');
        if (color.Length is not (6 or 8) || !uint.TryParse(color, NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var argb)) throw new ArgumentException("BackgroundColor must be #RRGGBB or #AARRGGBB.");
        var colorArgs = $"{(argb >> 16) & 255}, {(argb >> 8) & 255}, {argb & 255}, {(color.Length == 8 ? argb >> 24 : 255)}";
        var windowFactory = mainWindow == "Default" || mainWindow.Length == 0 ? null : prefix + TypeName(mainWindow);
        var aa = values.GetValueOrDefault("AntiAliasingSamples", "4");
        if (aa is not ("0" or "2" or "4" or "8" or "16")) throw new ArgumentException("AntiAliasingSamples must be 0, 2, 4, 8 or 16.");
        var filtering = values.GetValueOrDefault("TextureFiltering", "Anisotropic16x");
        if (filtering is not ("Bilinear" or "Trilinear" or "Anisotropic2x" or "Anisotropic4x" or "Anisotropic8x" or "Anisotropic16x")) throw new ArgumentException("Unknown texture filtering mode.");
        var assignments = new List<string>
        {
            $"FramesPerSecond = {Integer("FramesPerSecond", 60, 1000)}", $"Width = {Integer("Width", 1000)}", $"Height = {Integer("Height", 700)}",
            $"AntiAliasingSamples = {aa}", $"TextureFiltering = {prefix}ProjectZ.Shared.Drawing.TextureFiltering.{filtering}",
            $"MinimumWidth = {Integer("MinimumWidth", 320)}", $"MinimumHeight = {Integer("MinimumHeight", 200)}", $"AutoResizeViewport = {Bool("AutoResizeViewport", true)}",
            $"HardwareInput = {Bool("HardwareInput")}", $"DebugEnabled = {Bool("DebugEnabled")}", $"ConsoleEnabled = {Bool("ConsoleEnabled")}",
            $"ContentRoot = {Literal(values.GetValueOrDefault("ContentRoot", "Content"))}", $"BackgroundColor = {(vb ? "New " : "new ")}{prefix}Microsoft.Xna.Framework.Color({colorArgs})"
        };
        if (windowFactory != null) assignments.Add($"MainWindowFactory = {(vb ? "Function() New " : "() => new ")}{windowFactory}()");
        if (shutdown != "Default") assignments.Add("ShutdownMode = " + native + "ShutdownMode." + shutdown);
        if (vb) return "' <auto-generated>Project Properties > Project-Z controls startup.</auto-generated>\nNamespace Global.ProjectZGenerated\nPublic Module Application\nPublic ReadOnly Startup As New " + native + "ApplicationStartupOptions With {\n" + string.Join(",\n", assignments.Select(line => "    ." + line)) + "\n}\nPublic Sub Run(factory As System.Func(Of " + native + "Application), args As String())\n" + native + "Hosting.Run(factory, args, Startup)\nEnd Sub\n<System.STAThread>\nPublic Sub Main(args As String())\nRun(Function() New " + application + "(), args)\nEnd Sub\nEnd Module\nEnd Namespace\n";
        return "// <auto-generated>Project Properties > Project-Z controls startup.</auto-generated>\nnamespace ProjectZGenerated;\npublic static class Application\n{\n    public static " + native + "ApplicationStartupOptions Startup { get; } = new()\n    {\n" + string.Join(",\n", assignments.Select(line => "        " + line)) + "\n    };\n    public static void Run(System.Func<" + native + "Application> factory, string[] args) => " + native + "Hosting.Run(factory, args, Startup);\n    [System.STAThread] public static void Main(string[] args) => Run(() => new " + application + "(), args);\n}\n";
    }
    internal static string SettingsSchema(string templatePath, IEnumerable<string> windows)
    {
        var rule = XDocument.Load(templatePath); XNamespace ns = rule.Root!.Name.Namespace;
        rule.Descendants(ns + "BoolProperty").Single(element => (string?)element.Attribute("Name") == "ProjectZGenerateApplication").Remove();
        var property = rule.Descendants(ns + "StringProperty").Single(element => (string?)element.Attribute("Name") == "ProjectZMainWindow");
        property.Name = ns + "EnumProperty";
        property.Add(new XElement(ns + "EnumValue", new XAttribute("Name", "Default"), new XAttribute("DisplayName", "Preserve App.xaml startup")));
        foreach (var window in windows.Distinct().Order()) property.Add(new XElement(ns + "EnumValue", new XAttribute("Name", window), new XAttribute("DisplayName", window)));
        return rule.ToString();
    }
}
