    static string TranslatedType(ITypeSymbol type, bool vb)
    {
        if (type is IArrayTypeSymbol array) return TranslatedType(array.ElementType, vb) + (vb ? "(" : "[") + new string(',', array.Rank - 1) + (vb ? ")" : "]");
        if (type is IPointerTypeSymbol pointer) return TranslatedType(pointer.PointedAtType, vb) + "*";
        if (type is not INamedTypeSymbol named) return type.ToDisplayString(vb ? SymbolDisplayFormat.VisualBasicErrorMessageFormat : SymbolDisplayFormat.CSharpErrorMessageFormat);
        var prefix = vb ? "Global." : "global::";
        if (IsEmptyControl(named)) return prefix + Capabilities.Prefix + ".Controls.EmptyControl";
        var directName = named.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat);
        if (Capabilities.TypeAliases.TryGetValue(directName, out var alias)) return prefix + alias;
        if (directName.StartsWith("Microsoft.Win32.", StringComparison.Ordinal) && Capabilities.Translate(directName) != directName) return prefix + Capabilities.Translate(directName);
        var space = named.ContainingNamespace.IsGlobalNamespace ? "" : named.ContainingNamespace.ToDisplayString();
        if (Capabilities.IsWpfAssembly(named.ContainingAssembly?.Name)) space = Capabilities.Translate(space);
        var name = named.ContainingType != null ? TranslatedType(named.ContainingType, vb) + "." + named.Name : prefix + (space.Length > 0 ? space + "." : "") + named.Name;
        if (named.IsGenericType) name += (vb ? "(Of " : "<") + string.Join(", ", named.TypeArguments.Select(t => TranslatedType(t, vb))) + (vb ? ")" : ">");
        if (!vb && named.NullableAnnotation == NullableAnnotation.Annotated && named.IsReferenceType) name += "?";
        return name;
    }
    static bool IsEmptyControl(INamedTypeSymbol named)
    {
        if (!Capabilities.IsWpfAssembly(named.ContainingAssembly?.Name) || Capabilities.Types.Contains(named.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat)) || Capabilities.TypeAliases.ContainsKey(named.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat))) return false;
        for (var parent = named; parent != null; parent = parent.BaseType) if (parent.ToDisplayString() == "System.Windows.UIElement") return true;
        return false;
    }
    void ScanBinaryContracts(Compilation compilation, Project project)
    {
        foreach (var reference in compilation.References.OfType<PortableExecutableReference>())
        {
            if (compilation.GetAssemblyOrModuleSymbol(reference) is not IAssemblySymbol assembly) continue;
            var name = assembly.Name;
            if (reference.FilePath?.Contains("\\packs\\", StringComparison.OrdinalIgnoreCase) == true || project.Solution.Projects.Any(p => p.AssemblyName == name)) continue;
            if (Capabilities.IsWpfAssembly(name) || name.StartsWith("System") || name is "mscorlib" or "netstandard") continue;
            bool ExposesWpf(ITypeSymbol type) => Capabilities.IsWpfAssembly(type.ContainingAssembly?.Name) || type switch
            {
                IArrayTypeSymbol array => ExposesWpf(array.ElementType),
                IPointerTypeSymbol pointer => ExposesWpf(pointer.PointedAtType),
                INamedTypeSymbol named => named.TypeArguments.Any(ExposesWpf),
                _ => false
            };
            void Walk(INamespaceOrTypeSymbol container)
            {
                foreach (var member in container.GetMembers())
                {
                    if (member is INamespaceSymbol ns) Walk(ns);
                    else if (member is INamedTypeSymbol type && type.DeclaredAccessibility == Accessibility.Public)
                    {
                        // Only SDK types with an explicit native replacement may cross this boundary.
                        if (Capabilities.TypeAliases.ContainsKey(type.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat))) continue;
                        for (var parent = type.BaseType; parent != null; parent = parent.BaseType)
                            if (Capabilities.IsWpfAssembly(parent.ContainingAssembly.Name)) { issues.Add(new("PZI201", project.FilePath!, 1, 1, $"Binary {name}: {type} inherits {parent}; import its source or supply a native adapter.")); break; }
                        foreach (var api in type.GetMembers().Where(m => m.DeclaredAccessibility == Accessibility.Public))
                        {
                            IEnumerable<ITypeSymbol> types = api switch { IMethodSymbol m => m.Parameters.Select(p => p.Type).Append(m.ReturnType), IPropertySymbol p => [p.Type], IFieldSymbol f => [f.Type], IEventSymbol e => [e.Type], _ => [] };
                            if (types.Any(ExposesWpf)) issues.Add(new("PZI202", project.FilePath!, 1, 1, $"Binary {name}: {api} exposes WPF types; source conversion cannot rewrite this binary contract."));
                        }
                        Walk(type);
                    }
                }
            }
            Walk(assembly.GlobalNamespace);
        }
    }
