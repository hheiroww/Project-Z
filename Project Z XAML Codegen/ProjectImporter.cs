    static string ReplacePath(string value, string source, string destination)
    {
        if (source == "." || string.Equals(source, destination, StringComparison.OrdinalIgnoreCase)) return value;
        var pattern = "(?<![A-Za-z0-9_./\\\\-])" + System.Text.RegularExpressions.Regex.Escape(source).Replace("\\\\", "[\\\\/]") + "(?=$|[\\\\/'\";*])";
        return System.Text.RegularExpressions.Regex.Replace(value, pattern, _ => destination, System.Text.RegularExpressions.RegexOptions.IgnoreCase);
    }
