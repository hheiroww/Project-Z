    /// <summary>Recheck a codegen-owned import after updating its native runtime.</summary>
    internal static int VerifyExisting(string destination)
    {
        try { return new ProjectImporter { output = Path.GetFullPath(destination) }.VerifyExistingAsync().GetAwaiter().GetResult(); }
        catch (Exception error) { Console.Error.WriteLine(error.GetBaseException().Message); return 1; }
    }
    async Task<int> VerifyExistingAsync()
    {
        var manifest = Path.Combine(output, "projectz-import.manifest.json");
        var files = JsonSerializer.Deserialize<List<OwnedFile>>(File.ReadAllText(manifest)) ?? throw new InvalidDataException("The import manifest is empty.");
        // Validate every owned file before changing the compilation gate. An
        // edited source or stale report must be regenerated by the importer.
        foreach (var file in files)
        {
            var path = SafePath(file.Path);
            previousFiles.Add(file.Path, file);
            if (!File.Exists(path) || Hash(File.ReadAllBytes(path)) != file.Hash && !AllowedSettingsEdit(file.Path, File.ReadAllBytes(path))) throw new IOException("Refusing to verify modified generated file: " + path);
            previous.Add(file.Path, file.Hash);
        }
        using var report = JsonDocument.Parse(File.ReadAllText(Path.Combine(output, "projectz-import.report.json")));
        var root = report.RootElement;
        var previousIssues = root.GetProperty("Issues").Deserialize<Issue[]>() ?? [];
        if (previousIssues.Any(issue => issue.Code != "PZI900")) throw new InvalidOperationException("Resolve translator diagnostics and regenerate before verifying this import.");
        var project = Path.GetFullPath(root.GetProperty("RootProject").GetString()!);
        if (SafePath(Path.GetRelativePath(output, project)) != project) throw new InvalidDataException("The generated root project is outside the import.");
        var projectFiles = files.Where(file => Path.GetExtension(file.Path) is ".csproj" or ".vbproj").ToArray();
        void SetGate(bool blocked)
        {
            foreach (var file in projectFiles)
            {
                var document = XDocument.Load(SafePath(file.Path));
                foreach (var flag in document.Descendants("ProjectZImportHasErrors")) flag.Value = blocked ? "true" : "false";
                Write(file.Path, document.ToString());
            }
        }
        SetGate(false);
        (int Code, string Text) result;
        try { result = await Command("dotnet", ["build", project, "-c", "Release", "-m:1", "-nodeReuse:false", "-p:UseSharedCompilation=false", "-p:BuildInParallel=false", "-p:GeneratePackageOnBuild=false", "-p:DeployVst3OnBuild=false", "-p:ProjectZCodegenAlreadyRunning=true", "--nologo", "-v:minimal"]); }
        catch (Exception error) { result = (1, error.GetBaseException().Message); }
        Console.Write(result.Text);
        Issue[] diagnostics = result.Code == 0 ? [] : [new("PZI900", project, 1, 1, "Generated compilation failed:\n" + result.Text)];
        if (diagnostics.Length != 0) SetGate(true);
        var blanks = root.GetProperty("EmptyControls").Deserialize<string[]>() ?? [];
        Write("projectz-import.report.json", JsonSerializer.Serialize(new { Success = diagnostics.Length == 0, RootProject = project, EmptyControls = blanks, Issues = diagnostics }, JsonOptions));
        Write("projectz-import.unsupported.txt", "Project-Z generated import status: " + (diagnostics.Length == 0 ? "SUPPORTED" : "INCOMPLETE") + "\nGenerated root project: " + project + "\n" + string.Join("\n", diagnostics.Select(issue => issue.Code + ": " + issue.Message)) + "\n");
        File.WriteAllText(manifest, JsonSerializer.Serialize(files.Concat(owned).GroupBy(file => file.Path).Select(group => group.Last()).OrderBy(file => file.Path), JsonOptions));
        Console.WriteLine($"Project-Z verified import: {diagnostics.Length} diagnostic(s).");
        return diagnostics.Length == 0 ? 0 : 1;
    }
    internal static int GenerateForBuild(string input, string output, HashSet<string> sources)
    {
        if (!MSBuildLocator.IsRegistered) MSBuildLocator.RegisterDefaults();
        return new ProjectImporter { generateOnly = true, buildSources = sources }.Import(input, output).GetAwaiter().GetResult();
    }

    static readonly XNamespace X = "http://schemas.microsoft.com/winfx/2006/xaml";

    public static int Run(string[] args)
    {
        if ((args.Length != 3 && args.Length != 5) || args[1] != "--output" || args.Length == 5 && args[3] != "--root-directory") { Console.Error.WriteLine("Usage: ProjectZ.XamlCodegen import <csproj|vbproj> --output <directory> [--root-directory <folder-name>]"); return 2; }
        var importer = new ProjectImporter { rootDirectory = args.Length == 5 ? args[4] : null };
        try
        {
            if (!MSBuildLocator.IsRegistered) MSBuildLocator.RegisterDefaults();
            if (importer.rootDirectory is { } folder && (string.IsNullOrWhiteSpace(folder) || folder is "." or ".." || folder.IndexOfAny(Path.GetInvalidFileNameChars()) >= 0 || Path.IsPathRooted(folder))) throw new ArgumentException("The root directory must be a single valid folder name inside the output directory.");
            return importer.Import(Path.GetFullPath(args[0]), Path.GetFullPath(args[2])).GetAwaiter().GetResult();
        }
        catch (Exception error)
        {
            Console.Error.WriteLine(error.GetBaseException().Message);
            if (importer.output.Length > 0) importer.RecordFailure(args[0], error);
            return 1;
        }
    }
    void RecordFailure(string input, Exception error)
    {
        try
        {
            issues.Add(new("PZI000", input, 1, 1, error.GetBaseException().Message));
            Write("ProjectZ.Import.targets", "<Project><Target Name=\"CheckProjectZImport\" BeforeTargets=\"CoreCompile\"><Error Text=\"Project-Z import failed; see projectz-import.report.json.\" /></Target></Project>");
            Write("projectz-import.report.json", JsonSerializer.Serialize(new { Success = false, RootProject = input, Issues = issues }, JsonOptions));
            var files = previous.Select(p => previousFiles.GetValueOrDefault(p.Key) ?? new OwnedFile(p.Key, p.Value)).Concat(owned).GroupBy(p => p.Path).Select(g => g.Last()).OrderBy(p => p.Path);
            File.WriteAllText(Path.Combine(output, "projectz-import.manifest.json"), JsonSerializer.Serialize(files, JsonOptions));
        }
        catch (Exception reportError) { Console.Error.WriteLine("Could not update failure report without overwriting user edits: " + reportError.Message); }
    }
    async Task<int> Import(string input, string destination)
    {
        if (!File.Exists(input)) throw new FileNotFoundException("Source project", input);
        if (Path.GetExtension(input) is not (".csproj" or ".vbproj")) throw new ArgumentException("A C# or VB project is required.");
        if (destination.Equals(Path.GetDirectoryName(input), StringComparison.OrdinalIgnoreCase) || destination.StartsWith(Path.GetDirectoryName(input)! + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase)) throw new ArgumentException("Output must be outside the source project tree.");
        output = destination;
        var packaged = Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, ".."));
        if (File.Exists(Path.Combine(packaged, "ProjectZ.Tooling.props")))
        {
            portableTooling = packaged;
            codegenDirectory = packaged;
            compatibility = Path.Combine(packaged, "Runtime", "ProjectZ.WpfCompatibility.dll");
            if (!File.Exists(compatibility)) throw new FileNotFoundException("The portable XAML compatibility assembly is missing.", compatibility);
        }
        else
        {
            var repository = new DirectoryInfo(AppContext.BaseDirectory);
            while (repository != null && !File.Exists(Path.Combine(repository.FullName, "Project Z Windows.vbproj"))) repository = repository.Parent;
            compatibility = Path.Combine(repository?.FullName ?? throw new DirectoryNotFoundException("Cannot locate the Project-Z compatibility project or portable tooling."), "Project Z WPF Compatibility", "ProjectZ.WpfCompatibility.csproj");
            codegenDirectory = Path.Combine(repository.FullName, "Project Z XAML Codegen");
        }
        Directory.CreateDirectory(output);
        var manifest = Path.Combine(output, "projectz-import.manifest.json");
        if (File.Exists(manifest)) foreach (var entry in JsonSerializer.Deserialize<List<OwnedFile>>(File.ReadAllText(manifest)) ?? []) { previous.Add(entry.Path, entry.Hash); previousFiles.Add(entry.Path, entry); }
        // A whole-project export owns its portable build dependencies as well.
        // Build-time view generation uses the calling project's existing payload.
        if (portableTooling != null && !generateOnly)
            foreach (var relative in File.ReadAllLines(Path.Combine(portableTooling, "ProjectZ.Tooling.files")).Append("ProjectZ.Tooling.files").Distinct(StringComparer.OrdinalIgnoreCase))
            {
                var file = Path.GetFullPath(Path.Combine(portableTooling, relative));
                if (Path.IsPathRooted(relative) || !file.StartsWith(portableTooling + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase))
                    throw new InvalidDataException("A portable tooling manifest path escapes its directory.");
                WriteBytes(Path.Combine("ProjectZ", relative), File.ReadAllBytes(file));
            }
        using var workspace = MSBuildWorkspace.Create(new Dictionary<string, string> { ["Configuration"] = "Release" });
        using var workspaceDiagnostics = workspace.RegisterWorkspaceFailedHandler(e => { if (e.Diagnostic.Kind == WorkspaceDiagnosticKind.Failure) issues.Add(new("PZI001", input, 1, 1, e.Diagnostic.Message)); });
        Project root;
        try { root = await workspace.OpenProjectAsync(input); }
        catch (Exception error)
        {
            issues.Add(new("PZI001", input, 1, 1, "MSBuild could not load the source dependency graph: " + error.GetBaseException().Message));
            await InspectXamlGraph(input, new(StringComparer.OrdinalIgnoreCase));
            Write("ProjectZ.Import.targets", "<Project><Target Name=\"CheckProjectZImport\" BeforeTargets=\"CoreCompile\"><Error Text=\"Project-Z import failed to load source dependencies; see projectz-import.report.json.\" /></Target></Project>");
            Write("projectz-import.report.json", JsonSerializer.Serialize(new { Success = false, RootProject = input, Issues = issues }, JsonOptions));
            File.WriteAllText(manifest, JsonSerializer.Serialize(owned.GroupBy(x => x.Path).Select(g => g.Last()), JsonOptions));
            Console.Error.WriteLine($"Project-Z source loading failed; {issues.Count} diagnostics saved to {Path.Combine(output, "projectz-import.report.json")}");
            return 1;
        }
        await LoadBuildTargetProjects(workspace);
        root = workspace.CurrentSolution.GetProject(root.Id)!;
        foreach (var project in root.Solution.Projects)
        {
            var key = Path.GetFileNameWithoutExtension(project.FilePath) + "-" + Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(project.FilePath!)))[..8].ToLowerInvariant();
            if (project.Id == root.Id && rootDirectory != null) key = rootDirectory;
            projects[project.Id] = Path.Combine(output, key, Path.GetFileName(project.FilePath)!);
        }
        foreach (var project in root.Solution.Projects.OrderBy(p => p.FilePath, StringComparer.OrdinalIgnoreCase))
        {
            try { await ConvertProject(project); }
            catch (IOException) { throw; }
            catch (Exception error) { issues.Add(new("PZI004", project.FilePath!, 1, 1, error.GetBaseException().Message)); }
        }
        // Generated builds are gated by diagnostics. Never report an executable import while unsupported behavior remains.
        Write("ProjectZ.Import.targets", "<Project><Target Name=\"CheckProjectZImport\" BeforeTargets=\"CoreCompile\"><Error Condition=\"'$(ProjectZImportHasErrors)' == 'true'\" Text=\"Project-Z import has unsupported features; see projectz-import.report.json.\" /></Target></Project>");
        foreach (var project in projects.Values.Where(File.Exists))
        {
            var relative = Path.GetRelativePath(output, project);
            var xml = XDocument.Parse(File.ReadAllText(project));
            xml.Root!.AddFirst(new XElement("PropertyGroup", new XElement("ProjectZImportHasErrors", issues.Count != 0 ? "true" : "false")));
            Write(relative, xml.ToString());
        }
        if (issues.Count == 0 && !generateOnly)
        {
            var result = await Command("dotnet", ["build", projects[root.Id], "-c", "Release", "-m:1", "-nodeReuse:false", "-p:UseSharedCompilation=false", "-p:BuildInParallel=false", "-p:GeneratePackageOnBuild=false", "-p:DeployVst3OnBuild=false", "-p:ProjectZCodegenAlreadyRunning=true", "--nologo", "-v:minimal"]);
            if (result.Code != 0) issues.Add(new("PZI900", input, 1, 1, "Generated compilation failed:\n" + result.Text));
        }
        if (issues.Count != 0) foreach (var path in projects.Values.Where(File.Exists))
        {
            var xml = XDocument.Load(path);
            foreach (var flag in xml.Descendants("ProjectZImportHasErrors")) flag.Value = "true";
            Write(Path.GetRelativePath(output, path), xml.ToString());
        }
        Write("projectz-import.report.json", JsonSerializer.Serialize(new { Success = issues.Count == 0, RootProject = projects[root.Id], EmptyControls = emptyControls.Order(), Issues = issues.Distinct().OrderBy(i => i.File).ThenBy(i => i.Line).ThenBy(i => i.Column).ThenBy(i => i.Code) }, JsonOptions));
        Write("projectz-import.empty-controls.txt", "Empty Project-Z elements and optional native rendering projections:\n" + string.Join("\n", emptyControls.Order()) + "\n");
        Write("projectz-import.sources.json", JsonSerializer.Serialize(mappings, JsonOptions));
        var unsupported = new StringBuilder();
        unsupported.AppendLine("Project-Z generated import status: " + (issues.Count == 0 ? "SUPPORTED" : "INCOMPLETE"));
        unsupported.AppendLine("Source project: " + input);
        unsupported.AppendLine("Generated root project: " + projects[root.Id]);
        unsupported.AppendLine("Compatibility framework: " + compatibility);
        unsupported.AppendLine("Fix compatibility in Project-Z and regenerate; application source and generated application code require no manual edits.");
        foreach (var group in issues.Distinct().GroupBy(i => i.Code).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            unsupported.AppendLine(); unsupported.AppendLine(group.Key + ": " + group.Count() + " diagnostic(s)");
            foreach (var feature in group.GroupBy(i => i.Message).OrderBy(g => g.Key, StringComparer.Ordinal))
            {
                var example = feature.OrderBy(i => i.File, StringComparer.Ordinal).ThenBy(i => i.Line).ThenBy(i => i.Column).First();
                unsupported.AppendLine("  [" + feature.Count() + "] " + feature.Key);
                unsupported.AppendLine("    " + example.File + ":" + example.Line + ":" + example.Column);
            }
        }
        Write("projectz-import.unsupported.txt", unsupported.ToString());
        // Remove only unmodified files previously owned by this importer.
        foreach (var stale in previous.Keys.Except(owned.Select(f => f.Path), StringComparer.OrdinalIgnoreCase))
        {
            var path = SafePath(stale);
            if (File.Exists(path) && Hash(File.ReadAllBytes(path)) == previous[stale]) File.Delete(path);
        }
        File.WriteAllText(manifest, JsonSerializer.Serialize(owned.GroupBy(x => x.Path).Select(g => g.Last()).OrderBy(x => x.Path), JsonOptions));
        foreach (var issue in issues.Distinct().Take(80)) Console.Error.WriteLine($"{issue.File}({issue.Line},{issue.Column}): error {issue.Code}: {issue.Message}");
        Console.WriteLine($"Project-Z import: {projects.Count} project(s), {issues.Count} diagnostic(s). Report: {Path.Combine(output, "projectz-import.report.json")}");
        return issues.Count == 0 ? 0 : 1;
    }
    static readonly JsonSerializerOptions JsonOptions = new() { WriteIndented = true };
    async Task LoadBuildTargetProjects(MSBuildWorkspace workspace)
    {
        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        while (workspace.CurrentSolution.Projects.FirstOrDefault(p => p.FilePath != null && !seen.Contains(p.FilePath)) is { } project)
        {
            var input = project.FilePath!; seen.Add(input);
            var document = XDocument.Load(input, LoadOptions.SetLineInfo);
            foreach (var task in document.Descendants().Where(n => n.Name.LocalName == "MSBuild" && n.Ancestors().Any(a => a.Name.LocalName == "Target")))
            {
                var references = (string?)task.Attribute("Projects"); if (string.IsNullOrWhiteSpace(references)) continue;
                foreach (var reference in references.Split(';', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
                {
                    if (reference.Contains("$(") || reference.Contains("@("))
                    {
                        var line = (IXmlLineInfo)task;
                        issues.Add(new("PZI206", input, line.LineNumber, line.LinePosition, "A build target has a dynamic project dependency that cannot yet be relocated: " + reference));
                        continue;
                    }
                    var path = Path.GetFullPath(Path.Combine(Path.GetDirectoryName(input)!, reference));
                    if (Path.GetExtension(path) is not (".csproj" or ".vbproj")) continue;
                    if (!File.Exists(path)) { issues.Add(new("PZI203", input, 1, 1, "Missing build target project " + path)); continue; }
                    if (workspace.CurrentSolution.Projects.Any(p => string.Equals(p.FilePath, path, StringComparison.OrdinalIgnoreCase))) continue;
                    try { await workspace.OpenProjectAsync(path); }
                    catch (Exception error) { issues.Add(new("PZI002", input, 1, 1, "Could not import build target dependency " + path + ": " + error.GetBaseException().Message)); }
                }
            }
        }
    }
    async Task InspectXamlGraph(string project, HashSet<string> seen)
    {
        if (!seen.Add(project)) return;
        var result = await Command("dotnet", ["msbuild", project, "-nologo", "-p:Configuration=Release", "-getItem:Page,ApplicationDefinition,ProjectReference"]);
        if (result.Code != 0) { issues.Add(new("PZI002", project, 1, 1, result.Text)); return; }
        try
        {
            using var json = JsonDocument.Parse(result.Text); var items = json.RootElement.GetProperty("Items");
            foreach (var kind in new[] { "Page", "ApplicationDefinition" }) foreach (var item in items.GetProperty(kind).EnumerateArray())
            {
                var path = item.GetProperty("FullPath").GetString()!;
                if (File.Exists(path)) ValidateXaml(path, XDocument.Load(path, LoadOptions.SetLineInfo));
            }
            foreach (var reference in items.GetProperty("ProjectReference").EnumerateArray())
            {
                var path = reference.GetProperty("FullPath").GetString()!;
                if (File.Exists(path)) await InspectXamlGraph(path, seen); else issues.Add(new("PZI002", project, 1, 1, "Missing source dependency " + path));
            }
        }
        catch (Exception error) { issues.Add(new("PZI002", project, 1, 1, error.GetBaseException().Message)); }
    }
    async Task ConvertProject(Project project)
    {
        var input = project.FilePath!;
        var directory = Path.GetDirectoryName(input)!;
        var target = Path.GetDirectoryName(projects[project.Id])!;
        var prefix = Path.GetRelativePath(output, target);
        bool vb = project.Language == LanguageNames.VisualBasic;
        var result = await Command("dotnet", ["msbuild", input, "-nologo", "-p:Configuration=Release", "-getProperty:RootNamespace,AssemblyName,TargetFramework,DefineConstants,OptionStrict,OptionInfer,OptionExplicit,Nullable,LangVersion,AllowUnsafeBlocks,UseWindowsForms,OutputType,ImplicitUsings,PlatformTarget,Prefer32Bit,CheckForOverflowUnderflow,Optimize,DebugType,TreatWarningsAsErrors,NoWarn", "-getItem:None;Page;ApplicationDefinition;Resource;Content;EmbeddedResource;PackageReference;Reference;ProjectReference;Using;Import"]);
        if (result.Code != 0) { issues.Add(new("PZI002", input, 1, 1, result.Text)); return; }
        using var evaluation = JsonDocument.Parse(result.Text);
        var properties = evaluation.RootElement.GetProperty("Properties");
        var items = evaluation.RootElement.GetProperty("Items");
        string Property(string name) => properties.TryGetProperty(name, out var value) ? value.GetString() ?? "" : "";
        var pages = new List<(string Path, XDocument Doc)>();
        foreach (var kind in new[] { "Page", "ApplicationDefinition" })
            foreach (var item in items.GetProperty(kind).EnumerateArray())
            {
                var path = item.GetProperty("FullPath").GetString()!;
                if (!File.Exists(path)) continue;
                var doc = XDocument.Load(path, LoadOptions.SetLineInfo); pages.Add((path, doc)); ValidateXaml(path, doc);
            }
        var compilation = await project.GetCompilationAsync() ?? throw new InvalidOperationException("Cannot compile source model.");
        var compatibilityDll = portableTooling != null ? compatibility : Path.Combine(Path.GetDirectoryName(compatibility)!, "bin", "Release", "net8.0-windows7.0", "ProjectZ.WpfCompatibility.dll");
        Compilation? adapterModel = File.Exists(compatibilityDll) ? compilation.AddReferences(MetadataReference.CreateFromFile(compatibilityDll)) : null;
        if (adapterModel != null && adapterModel.GetTypeByMetadataName("System.Windows.Forms.IDataObject") == null)
        {
            var formsReference = compilation.References.Select(reference => reference.Display).Where(path => path != null).Select(path => Path.Combine(Path.GetDirectoryName(path!)!, "System.Windows.Forms.dll")).FirstOrDefault(File.Exists);
            if (formsReference != null) adapterModel = adapterModel.AddReferences(MetadataReference.CreateFromFile(formsReference));
        }
        // Supply the normal WPF designer surface for semantic analysis when the project has never been built.
        foreach (var page in pages)
        {
            string? className = (string?)page.Doc.Root?.Attribute(X + "Class");
            if (className == null || (!Capabilities.Controls.Contains(page.Doc.Root!.Name.LocalName) && page.Doc.Root.Name.LocalName != "Application")) continue;
            var fullName = vb && Property("RootNamespace").Length > 0 ? Property("RootNamespace") + "." + className : className;
            var type = compilation.GetTypeByMetadataName(fullName);
            if (type?.GetMembers("InitializeComponent").Length > 0) continue;
            var text = page.Doc.Root.Name.LocalName == "Application" ? ApplicationDesigner(className, vb, "", null, true, true) : Designer(page.Doc, className, vb, "", original: true, type?.BaseType?.SpecialType != SpecialType.System_Object && type?.BaseType != null);
            compilation = compilation.AddSyntaxTrees(vb ? VB.VisualBasicSyntaxTree.ParseText(text, (VB.VisualBasicParseOptions?)project.ParseOptions) : CS.CSharpSyntaxTree.ParseText(text, (CS.CSharpParseOptions?)project.ParseOptions));
        }
        bool needsCompatibility = pages.Count > 0;
        bool desktopAutomation = false;
        var compileFiles = new List<string>();
        var contentFiles = new List<string>();
        var relocatedFiles = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var tree in compilation.SyntaxTrees.Where(t => !string.IsNullOrEmpty(t.FilePath) && !IsGenerated(t.FilePath)).OrderBy(t => t.FilePath))
        {
            if (generateOnly && !buildSources!.Contains(tree.FilePath)) continue;
            var relative = SourceRelative(directory, tree.FilePath);
            var generated = Path.Combine(prefix, "Source", relative);
            var model = compilation.GetSemanticModel(tree);
            var changes = new List<TextChange>();
            var root = await tree.GetRootAsync();
            Visit(root);
            void Visit(SyntaxNode node)
            {
                // WPF controls did not expose Dispose. Preserve an application's
                // own IDisposable method when the native adapter adds that member.
                if (node is CS.Syntax.MethodDeclarationSyntax method && method.Identifier.ValueText == "Dispose" && method.ParameterList.Parameters.Count == 0 && method.ExplicitInterfaceSpecifier == null &&
                    method.Modifiers.Any(token => token.RawKind == (int)CS.SyntaxKind.PublicKeyword) && !method.Modifiers.Any(token => token.RawKind is (int)CS.SyntaxKind.StaticKeyword or (int)CS.SyntaxKind.OverrideKeyword or (int)CS.SyntaxKind.NewKeyword) &&
                    model.GetDeclaredSymbol(method) is IMethodSymbol { ReturnsVoid: true } disposal && disposal.ContainingType.AllInterfaces.Any(type => type.ToDisplayString() == "System.IDisposable"))
                {
                    for (var baseType = disposal.ContainingType.BaseType; baseType != null; baseType = baseType.BaseType)
                        if (baseType.ToDisplayString() == "System.Windows.FrameworkElement") { changes.Add(new(new TextSpan(method.ReturnType.SpanStart, 0), "new ")); break; }
                }
                if (node is CS.Syntax.IdentifierNameSyntax or VB.Syntax.IdentifierNameSyntax)
                {
                    var member = model.GetSymbolInfo(node).Symbol;
                    if (member is IMethodSymbol or IPropertySymbol or IFieldSymbol or IEventSymbol && (Capabilities.IsWpfAssembly(member.ContainingAssembly?.Name) || Capabilities.TypeAliases.ContainsKey(member.ContainingType.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat))))
                    {
                        var ownerName = member.ContainingType.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat);
