    static string Designer(XDocument document, string className, bool vb, string path, bool original, bool hasBase, bool hasConstructor = true)
    {
        if (!original) { document = new XDocument(document); MarkupTranslation.Translate(document); }
        var root = document.Root!; var split = className.LastIndexOf('.'); var ns = split < 0 ? "" : className[..split]; var name = split < 0 ? className : className[(split + 1)..];
        var prefix = original ? "System.Windows" : Capabilities.Prefix;
        string Type(string n) => original && n is "WebView2" or "WebView2CompositionControl" ? (vb ? "Global." : "global::") + "Microsoft.Web.WebView2.Wpf." + n : (vb ? "Global." : "global::") + prefix + (n == "Window" ? ".Window" : n is "Polygon" or "Rectangle" or "Ellipse" or "Path" or "Line" or "Polyline" ? ".Shapes." + n : ".Controls." + n);
        string NodeType(XElement node)
        {
            var nativeType = (string?)node.Attribute(XName.Get("Type", "urn:projectz:import"));
            if (nativeType != null) return (vb ? "Global." : "global::") + nativeType;
            if (node.Name.NamespaceName.StartsWith("clr-namespace:") && !node.Name.NamespaceName.StartsWith("clr-namespace:System.Windows")) return (vb ? "Global." : "global::") + node.Name.NamespaceName[14..].Split(';')[0] + "." + node.Name.LocalName;
            if (node.Name.LocalName is "RotateTransform" or "ScaleTransform" or "TranslateTransform" or "TransformGroup" or "LinearGradientBrush" or "RadialGradientBrush" or "SolidColorBrush" or "ImageBrush" or "GradientStop" or "RectangleGeometry") return (vb ? "Global." : "global::") + prefix + ".Media." + node.Name.LocalName;
            return Type(node.Name.LocalName);
        }
        string Quote(string text) => vb ? "\"" + text.Replace("\"", "\"\"") + "\"" : JsonSerializer.Serialize(text);
        bool NamedObject(XElement node) => node.Attribute(X + "Name") != null && node.Name.LocalName is "RotateTransform" or "ScaleTransform" or "TranslateTransform" or "TransformGroup" or "LinearGradientBrush" or "RadialGradientBrush" or "SolidColorBrush" or "ImageBrush" or "GradientStop" or "RectangleGeometry" && !node.Ancestors().Any(parent => parent.Name.LocalName is "Style" or "DataTemplate" or "ControlTemplate");
        var nodes = root.DescendantsAndSelf().Where(n => NamedObject(n) || Capabilities.IsVisualObject(n) || n.Name.LocalName is "RowDefinition" or "ColumnDefinition" && n.Attribute(X + "Name") != null && !n.Ancestors().Any(p => p.Name.LocalName is "Style" or "DataTemplate" or "ControlTemplate" or "ResourceDictionary" || p.Name.LocalName.EndsWith(".Resources", StringComparison.Ordinal)) || original && (n.Name.NamespaceName == "http://schemas.microsoft.com/winfx/2006/xaml/presentation" || n.Name.NamespaceName.StartsWith("clr-namespace:")) && MarkupTranslation.IsVisualDeclaration(n) && !n.Ancestors().Any(p => p.Name.LocalName is "Style" or "DataTemplate" or "ControlTemplate" or "ResourceDictionary" || p.Name.LocalName.EndsWith(".Resources", StringComparison.Ordinal))).Select(n => (Node: n, Name: (string?)n.Attribute(X + "Name") ?? (string?)n.Attribute("Name"))).ToList();
        var usedNames = nodes.Where(n => n.Name != null).Select(n => n.Name!).ToHashSet(StringComparer.Ordinal);
        var autoNames = new Dictionary<XElement, string>(); int autoIndex = 0;
        foreach (var node in nodes.Where(n => n.Name == null)) { while (usedNames.Contains("__pz" + autoIndex)) autoIndex++; autoNames[node.Node] = "__pz" + autoIndex++; }
        var sb = new StringBuilder();
        if (vb)
        {
            if (ns.Length > 0) sb.AppendLine("Namespace " + ns);
            sb.AppendLine($"Partial Public Class [{name}]");
            if (!hasBase) sb.AppendLine("Inherits " + Type(root.Name.LocalName));
            foreach (var n in nodes.Where(n => n.Name != null)) sb.AppendLine($"Friend WithEvents [{n.Name}] As {NodeType(n.Node)}");
            if (!original && !hasConstructor) sb.AppendLine("Public Sub New()\nInitializeComponent()\nEnd Sub");
            if (!original) sb.AppendLine("Private _projectZInitialized As Boolean");
            sb.AppendLine("Private Sub InitializeComponent()");
            if (!original)
            {
                sb.AppendLine("If _projectZInitialized Then Return\n_projectZInitialized = True");
                sb.AppendLine($"Global.{Capabilities.Prefix}.XamlLoader.Initialize(Me, {Quote(path)})");
                foreach (var n in nodes.Where(n => n.Name != null)) sb.AppendLine($"Me.[{n.Name}] = DirectCast(Me.FindName({Quote(n.Name!)}), {NodeType(n.Node)})");
            }
            sb.AppendLine("End Sub\nEnd Class"); if (ns.Length > 0) sb.AppendLine("End Namespace");
        }
        else
        {
            if (ns.Length > 0) sb.AppendLine("namespace " + ns + " {");
            sb.AppendLine($"public partial class @{name}" + (hasBase ? "" : " : " + Type(root.Name.LocalName)) + " {");
            foreach (var n in nodes.Where(n => n.Name != null)) sb.AppendLine($"internal {NodeType(n.Node)} @{n.Name} = null!;");
            if (!original && !hasConstructor) sb.AppendLine($"public @{name}() {{ InitializeComponent(); }}");
            if (!original) sb.AppendLine("private bool _projectZInitialized;");
            sb.AppendLine("private void InitializeComponent() {");
            if (!original)
            {
                sb.AppendLine("if (_projectZInitialized) return; _projectZInitialized = true;");
                sb.AppendLine($"global::{Capabilities.Prefix}.XamlLoader.Initialize(this, {Quote(path)});");
                foreach (var n in nodes.Where(n => n.Name != null)) sb.AppendLine($"this.@{n.Name} = ({NodeType(n.Node)})FindName({Quote(n.Name!)})!;");
            }
            sb.AppendLine("}\n}"); if (ns.Length > 0) sb.AppendLine("}");
        }
        return sb.ToString();
    }
