    static string? SettingsStructureHash(string path, byte[] contents)
    {
        if (Path.GetExtension(path) is not (".csproj" or ".vbproj")) return null;
        var document = XDocument.Parse(Encoding.UTF8.GetString(contents).TrimStart('\uFEFF'));
        foreach (var group in document.Root!.Elements("PropertyGroup").ToArray())
        {
            group.Elements().Where(element => StartupSettings.Contains(element.Name.LocalName)).Remove();
            if (!group.HasElements && !group.Nodes().Any(node => node is XComment)) group.Remove();
        }
        return Hash(Encoding.UTF8.GetBytes(document.ToString(SaveOptions.DisableFormatting)));
    }
    bool AllowedSettingsEdit(string relative, byte[] contents) => previousFiles.TryGetValue(relative, out var file) && file.SettingsStructureHash != null && file.SettingsStructureHash == SettingsStructureHash(relative, contents);
    readonly Dictionary<ProjectId, string> projects = new();
