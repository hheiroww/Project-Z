using System.Text;
using System.Xml;
using System.Xml.Linq;

// Native scene templates are compiled directly into the owning partial class.
// They neither load markup at runtime nor wrap controls in compatibility objects.
internal static class NativeSceneCompiler
{
    internal static readonly Dictionary<string, string> Overrides = new()
    {
        ["Height"] = "float", ["Font"] = "string", ["TextPadding"] = "Vector2", ["CornerRadius"] = "float",
        ["BorderThickness"] = "float", ["BorderColor"] = "Color", ["BackgroundColor"] = "Color", ["ForegroundColor"] = "Color",
        ["MouseOverBackgroundColor"] = "Color", ["MouseDownBackgroundColor"] = "Color", ["MaxWidth"] = "float", ["MaxHeight"] = "float",
        ["Clip"] = "bool", ["IsOverlay"] = "bool", ["AutoSizeWidthOnTextOverflow"] = "bool", ["TextWrapping"] = "TextWrapping", ["TextTrimming"] = "TextTrimming"
    };
    internal static readonly XNamespace X = "http://schemas.microsoft.com/winfx/2006/xaml";
    internal static string Required(XElement e, string name) => (string?)e.Attribute(name) ?? throw Error(e, $"Missing {name}.");
    internal static Exception Error(XElement e, string message) => new InvalidDataException($"{e.BaseUri}({((IXmlLineInfo)e).LineNumber}): {message}");
    internal static string Identifier(string value) => value.Length > 0 && (char.IsLetter(value[0]) || value[0] == '_') && value.All(c => char.IsLetterOrDigit(c) || c == '_') ? value : throw new InvalidDataException($"Invalid C# identifier: {value}");
    internal static string Quote(string value) => System.Text.Json.JsonSerializer.Serialize(value);
    internal static string Expression(string value, string type)
    {
        if (value.StartsWith("{Expression ") && value.EndsWith('}')) return value[12..^1];
        if (value.StartsWith("{Parameter ") && value.EndsWith('}')) return Identifier(value[11..^1]);
        if (value.StartsWith("{Resource ") && value.EndsWith('}')) return Identifier(value[10..^1]);
        return type switch
        {
            "string" => Quote(value),
            "bool" => bool.Parse(value) ? "true" : "false",
            "Vector2" when !value.StartsWith('{') => "new Vector2(" + string.Join(", ", value.Split(',').Select(v => Expression(v.Trim(), "float"))) + ")",
            "Color" or "Color?" when value.StartsWith('#') => Color(value),
            "float" => float.Parse(value, System.Globalization.CultureInfo.InvariantCulture).ToString("R", System.Globalization.CultureInfo.InvariantCulture) + "f",
            "double" => double.Parse(value, System.Globalization.CultureInfo.InvariantCulture).ToString("R", System.Globalization.CultureInfo.InvariantCulture) + "d",
            _ => value
        };
    }
    static string Color(string value)
    {
        var hex = value[1..];
        if (hex.Length != 6 && hex.Length != 8) throw new InvalidDataException("Colors require #RRGGBB or #AARRGGBB.");
        int offset = hex.Length == 8 ? 2 : 0;
        int Byte(int start) => Convert.ToInt32(hex.Substring(start, 2), 16);
        return $"new Color({Byte(offset)}, {Byte(offset + 2)}, {Byte(offset + 4)}, {(offset == 2 ? Byte(0) : 255)})";
    }
    internal static List<XElement> Parameters(XElement factory) => factory.Elements().Where(e => e.Name.LocalName == "Parameter").ToList();
    internal static string Name(XElement e) => Identifier((string?)e.Attribute(X + "Name") ?? Required(e, "Name"));
    internal static int Run(string manifest)
    {
        try
        {
            var directory = Path.GetDirectoryName(Path.GetFullPath(manifest))!;
            var paths = File.ReadAllLines(manifest).Where(p => !string.IsNullOrWhiteSpace(p)).ToArray();
            var docs = paths.Select(p => XDocument.Load(p, LoadOptions.SetLineInfo | LoadOptions.SetBaseUri)).ToArray();
            var groups = docs.GroupBy(d => Required(d.Root!, "Class"));
            var files = new List<string>();
            foreach (var group in groups)
            {
                var className = group.Key;
                var split = className.LastIndexOf('.');
                var ns = split < 0 ? null : className[..split];
                var name = Identifier(className[(split + 1)..]);
                var nodes = group.SelectMany(d => d.Root!.Elements()).ToArray();
                var factories = nodes.Where(e => e.Name.LocalName == "Factory").ToDictionary(Name);
                var code = new StringBuilder("// <auto-generated by Project-Z native XAML; edit the .xaml source />\n#nullable enable\n");
                foreach (var use in group.SelectMany(d => d.Root!.Elements().Where(e => e.Name.LocalName == "Using")).Select(e => System.Text.RegularExpressions.Regex.Replace(e.Value.Trim(), @"\s*=\s*", " = ")).Distinct()) code.AppendLine($"using {use};");
                if (ns != null) code.AppendLine($"namespace {ns};");
                code.AppendLine($"partial class {name}\n{{");
                var sizes = group.SelectMany(d => d.Descendants().Attributes()).Select(a => a.Name.LocalName == "FontSize" && int.TryParse(a.Value, out var size) ? size
                    : a.Name.LocalName is "Value" or "Font" && System.Text.RegularExpressions.Regex.Match(a.Value, @"^[\w.-]+_(\d+)$") is { Success: true } match ? int.Parse(match.Groups[1].Value) : 0).Where(s => s > 0).Distinct().OrderBy(s => s);
                code.AppendLine($"    internal static readonly int[] ProjectZNativeXamlFontSizes = {{ {string.Join(", ", sizes)} }};");
                var symbols = new HashSet<string>();
                foreach (var node in nodes.Where(e => e.Name.LocalName != "Using"))
                {
                    var id = Name(node);
                    if (!symbols.Add(id)) throw Error(node, $"Duplicate name {id}.");
                    code.AppendLine($"#line {((IXmlLineInfo)node).LineNumber} {Quote(new Uri(node.BaseUri).LocalPath)}");
                    switch (node.Name.LocalName)
                    {
                        case "Resource":
                            var type = Required(node, "Type");
                            code.AppendLine($"    private static readonly {type} {id} = {Expression(Required(node, "Value"), type)};");
                            break;
                        case "Factory":
                            if ((string?)node.Attribute("External") == "true") break;
                            EmitFactory(code, node, id);
                            break;
                        case "ObjectFactory":
                            EmitObjectFactory(code, node, id);
                            break;
                        default:
                            var factoryName = Required(node, "Factory");
                            if (!factories.TryGetValue(factoryName, out var factory)) throw Error(node, $"Unknown factory {factoryName}.");
                            var factoryAttributes = Parameters(factory).Select(p => (string?)p.Attribute("Attribute") ?? Required(p, "Name")).ToHashSet();
                            var allowed = factoryAttributes.Concat(Overrides.Keys).Concat(new[] { "Factory", "Page", "AutoCreate" }).ToHashSet();
                            foreach (var attribute in node.Attributes().Where(a => !a.IsNamespaceDeclaration && a.Name != X + "Name"))
                                if (!allowed.Contains(attribute.Name.LocalName)) throw Error(node, $"Unknown property {attribute.Name.LocalName} for {factoryName}.");
                            var parameters = node.Elements().Where(e => e.Name.LocalName == "Parameter").ToArray();
                            var args = Parameters(factory).Select(p =>
                            {
                                var key = (string?)p.Attribute("Attribute") ?? Required(p, "Name");
                                var value = (string?)node.Attribute(key) ?? (string?)p.Attribute("Default") ?? throw Error(node, $"Missing {key}.");
                                return Expression(value, Required(p, "Type"));
                            });
                            var signature = $"    private {Required(factory, "Returns")} {id}({string.Join(", ", parameters.Select(p => Required(p, "Type") + " " + Identifier(Required(p, "Name"))))})";
                            var overrides = node.Attributes().Where(a => Overrides.ContainsKey(a.Name.LocalName) && !factoryAttributes.Contains(a.Name.LocalName)).ToArray();
                            if (overrides.Length == 0) code.AppendLine($"{signature} => {factoryName}({string.Join(", ", args)});");
                            else
                            {
                                if (Required(factory, "Returns") == "void") throw Error(node, "Property overrides require an element-returning factory.");
                                code.AppendLine($"{signature}\n    {{\n        var element = {factoryName}({string.Join(", ", args)});");
                                foreach (var property in overrides)
                                {
                                    var expression = Expression(property.Value, Overrides[property.Name.LocalName]);
                                    code.AppendLine(property.Name.LocalName == "Height" ? $"        element.Size = new Microsoft.Xna.Framework.Vector2(element.Size.X, {expression});" : $"        element.{property.Name.LocalName} = {expression};");
                                }
                                code.AppendLine("        return element;\n    }");
                            }
                            break;
                    }
                    code.AppendLine("#line default");
                }
                code.AppendLine("    internal void ProjectZCreateAdditionalControls(System.Action<string?, System.Action> attach)\n    {");
                foreach (var extra in nodes.Where(e => (string?)e.Attribute("AutoCreate") == "true"))
                {
                    if (Parameters(extra).Count != 0) throw Error(extra, "Auto-created controls cannot require code-behind parameters.");
                    var page = extra.Attribute("Page") is {} pageName ? Quote(pageName.Value) : "null";
                    code.AppendLine($"        attach({page}, () => {Name(extra)}());");
                }
                code.AppendLine("    }");
                code.AppendLine("}");
                var output = Path.Combine(directory, className + ".NativeXaml.g.cs");
                if (!File.Exists(output) || File.ReadAllText(output) != code.ToString()) File.WriteAllText(output, code.ToString());
                files.Add(output);
            }
            File.WriteAllLines(Path.Combine(directory, "native-compile-items"), files);
            Console.WriteLine($"Project-Z native XAML: {paths.Length} files, {files.Count} partial classes.");
            return 0;
        }
        catch (Exception e) { Console.Error.WriteLine(e.Message); return 1; }
    }

    static void EmitFactory(StringBuilder code, XElement factory, string name)
    {
        var returns = Required(factory, "Returns");
        var args = Parameters(factory).Select(p => Required(p, "Type") + " " + Identifier(Required(p, "Name")) + (p.Attribute("Default") is {} d ? " = " + Expression(d.Value, Required(p, "Type")) : ""));
        code.AppendLine($"    private {returns} {name}({string.Join(", ", args)})\n    {{");
        var element = factory.Elements().Single(e => e.Name.LocalName == "Element");
        code.AppendLine($"        var element = new {Required(element, "Type")}(this)");
        code.AppendLine("        {");
        foreach (var set in element.Elements().Where(e => e.Name.LocalName == "Set"))
            code.AppendLine($"            {Identifier(Required(set, "Property"))} = {Expression(Required(set, "Value"), Required(set, "Type"))},");
        code.AppendLine("        };");
        foreach (var hook in element.Elements().Where(e => e.Name.LocalName == "Event"))
        {
            var action = Expression(Required(hook, "Action"), "Action");
            var when = (string?)hook.Attribute("When");
            code.AppendLine($"        element.{Identifier(Required(hook, "Name"))} += _ => {{ {(when == null ? "" : $"if ({when}) ")} {action}(); }};");
        }
        if (element.Attribute("Created") is {} created) code.AppendLine($"        {Identifier(created.Value)}(element{(element.Attribute("CreatedArguments") is {} extra ? ", " + extra.Value : "")});");
        if (factory.Attribute("Attach") is {} attach) code.AppendLine($"        {Identifier(attach.Value)}(element);");
        if (returns != "void") code.AppendLine("        return element;");
        code.AppendLine("    }");
    }

    static void EmitObjectFactory(StringBuilder code, XElement node, string name)
    {
        var type = Required(node, "Type");
        var parameters = Parameters(node).Select(p => Required(p, "Type") + " " + Identifier(Required(p, "Name")));
        var arguments = node.Elements().Where(e => e.Name.LocalName == "Argument").Select(e => Expression(Required(e, "Value"), Required(e, "Type")));
        code.AppendLine($"    private {((string?)node.Attribute("Static") == "true" ? "static " : "")}{type} {name}({string.Join(", ", parameters)}) => new {type}({string.Join(", ", arguments)})");
        code.AppendLine("    {");
        foreach (var set in node.Elements().Where(e => e.Name.LocalName == "Set"))
            code.AppendLine($"        {Identifier(Required(set, "Property"))} = {Expression(Required(set, "Value"), Required(set, "Type"))},");
        code.AppendLine("    };");
    }
}
